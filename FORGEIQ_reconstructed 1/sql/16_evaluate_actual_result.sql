SELECT
    SUM(IFF(FAILURE_NEXT_6H=1 AND PREDICTED_CLASS=1,1,0)) TRUE_POSITIVES,
    SUM(IFF(FAILURE_NEXT_6H=1 AND PREDICTED_CLASS=0,1,0)) FALSE_NEGATIVES,
    SUM(IFF(FAILURE_NEXT_6H=0 AND PREDICTED_CLASS=1,1,0)) FALSE_POSITIVES,
    SUM(IFF(FAILURE_NEXT_6H=0 AND PREDICTED_CLASS=0,1,0)) TRUE_NEGATIVES
FROM FORGEIQ.ANALYTICS.PRODUCTION_PREDICTIONS;
