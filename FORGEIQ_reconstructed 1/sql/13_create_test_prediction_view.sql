CREATE OR REPLACE VIEW FORGEIQ.ANALYTICS.TEST_PREDICTIONS AS
SELECT
    ASSET_ID,
    HOUR,
    FAILURE_NEXT_6H,
    prediction:class::NUMBER AS PREDICTED_CLASS,
    prediction:probability['1']::FLOAT AS FAILURE_PROBABILITY
FROM (
    SELECT *, FORGEIQ.ANALYTICS.FAILURE_PREDICTOR_V2!PREDICT(INPUT_DATA => {*}) AS prediction
    FROM FORGEIQ.ANALYTICS.ML_TEST_VIEW
);
